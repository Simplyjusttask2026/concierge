"""Explicit, owner-operated adapters. Browser locators must be verified on the Dell.
Never let a model, inbox message or website call these functions directly.
"""
import email
from email.message import EmailMessage
from email.policy import default
from email.utils import parseaddr
import imaplib
import json
import os
import smtplib
import ssl
import time
from urllib.parse import urlparse

ALLOWED = ('nextdoor.com', 'facebook.com', 'instagram.com', 'linkedin.com',
           'youtube.com', 'tiktok.com', 'x.com', 'twitter.com', 'zoho.com', 'zoho.eu')


def allowed_url(url):
    p = urlparse(url)
    host = (p.hostname or '').lower()
    if p.scheme != 'https' or p.username or p.password or p.port not in (None, 443):
        raise ValueError('Only HTTPS account URLs without embedded credentials are allowed.')
    if not any(host == h or host.endswith('.' + h) for h in ALLOWED):
        raise ValueError('Unknown account host. No arbitrary URLs or paid providers.')
    return host


class Browser:
    def __init__(self, store):
        self.store = store
        self.manager = None
        self.ctx = None
        self.page = None

    def __enter__(self):
        self.store.check_stop()
        from playwright.sync_api import sync_playwright
        self.manager = sync_playwright().start()
        try:
            self.ctx = self.manager.chromium.launch_persistent_context(
                str(self.store.data / 'browser_profile'), headless=False,
                viewport={'width': 1280, 'height': 900}, accept_downloads=False)
            self.page = self.ctx.pages[0] if self.ctx.pages else self.ctx.new_page()
            return self
        except Exception:
            self.manager.stop()
            raise

    def __exit__(self, *exc):
        try:
            if self.ctx: self.ctx.close()
        finally:
            if self.manager: self.manager.stop()

    def navigate(self, url):
        original = allowed_url(url)
        self.store.check_stop()
        self.page.goto(url, wait_until='domcontentloaded', timeout=60000)
        self.page.wait_for_timeout(2500)
        if allowed_url(self.page.url) != original:
            raise RuntimeError('Unexpected redirected account host. Owner must verify login.')
        path = urlparse(self.page.url).path.lower()
        if any(x in path for x in ['/login', '/signin', '/checkpoint', '/challenge', '/captcha']):
            raise RuntimeError('Login/security check requires the owner. No bypass attempted.')

    def read(self, config):
        self.navigate(config['url'])
        selector = config.get('item_selector', 'article')
        items = self.page.locator(selector)
        if not items.count():
            raise RuntimeError('No configured items found. Verify login and selectors; not a zero-lead success.')
        output = []
        for i in range(min(items.count(), 40)):
            self.store.check_stop()
            item = items.nth(i)
            text = item.inner_text(timeout=5000).strip()
            if not text: continue
            # Never invent permalinks. Missing permalink requires manual correction before send.
            link_selector = config.get('permalink_selector')
            href = item.locator(link_selector).first.get_attribute('href') if link_selector and item.locator(link_selector).count() else None
            if href:
                from urllib.parse import urljoin
                url = urljoin(self.page.url, href)
                allowed_url(url)
            else:
                url = self.page.url
            output.append({'text': text[:30000], 'url': url})
        return output


def browser_send(store, row, confirm_fn):
    # Config for an action is user-verified; selectors are not guessed or generated by an LLM.
    cfg = store.config().get('browser_actions', {}).get(row['channel'] + ':' + row['kind'])
    if not cfg or cfg.get('verified_on_dell') is not True:
        raise RuntimeError('No owner-verified send adapter for this channel/action. Nothing sent.')
    required = ['editor_selector', 'submit_selector', 'context_selector', 'success_selector']
    if any(not cfg.get(k) for k in required):
        raise RuntimeError('Adapter needs editor, submit, recipient/context and success locators.')
    if not row['source'] or 'REVIEW REQUIRED' in row['recipient']:
        raise ValueError('Create a reviewed draft with exact recipient and source context first.')
    host = allowed_url(row['target'])
    if host != cfg.get('host'):
        raise ValueError('Draft target host does not match the verified adapter.')
    with Browser(store) as browser:
        browser.navigate(row['target'])
        page = browser.page
        context = page.locator(cfg['context_selector'])
        if context.count() != 1 or row['recipient'] not in context.inner_text():
            raise RuntimeError('Recipient/context mismatch. Nothing sent.')
        # Exact source excerpt is owner-selected; catches wrong post or changed thread.
        if row['source'] not in page.locator('body').inner_text():
            raise RuntimeError('Source context changed or missing. Re-read and draft again.')
        editor = page.locator(cfg['editor_selector'])
        submit = page.locator(cfg['submit_selector'])
        success = page.locator(cfg['success_selector'])
        if editor.count() != 1 or submit.count() != 1:
            raise RuntimeError('Ambiguous editor or submit control. Nothing sent.')
        if success.is_visible():
            raise RuntimeError('Success indicator already present; cannot verify a new send.')
        print('Review the live browser and queued action. No submit has been clicked.')
        if not confirm_fn(row):
            print('Cancelled; nothing sent.'); return
        store.check_stop()
        # Fill only after exact owner approval; Enter/hotkeys are never used to send.
        editor.fill(row['body'])
        current = editor.evaluate('(el) => el.value === undefined ? el.innerText : el.value')
        if current.strip() != row['body'].strip():
            raise RuntimeError('Editor content differs. No submit clicked.')
        if row['recipient'] not in context.inner_text():
            raise RuntimeError('Context changed. Nothing sent.')
        store.claim(row['id'])
        try:
            store.check_stop()
            submit.click(timeout=10000)
            success.wait_for(state='visible', timeout=15000)
            store.finish(row['id'], 'sent_verified', 'New configured success indicator visible; verify in account.')
            print('Submit completed and configured success indicator verified. Review in account.')
        except Exception:
            store.finish(row['id'], 'uncertain', 'May or may not have sent. Inspect account manually; DO NOT retry automatically.')
            raise


def email_config(store):
    cfg = store.config().get('email', {})
    if not cfg.get('enabled'):
        raise RuntimeError('Email disabled. No account access attempted.')
    password = os.environ.get('SJT_ZOHO_MAIL_PASSWORD', '')
    if not cfg.get('user') or not password:
        raise RuntimeError('Set your mail user locally and app password in SJT_ZOHO_MAIL_PASSWORD, never in chat/GitHub.')
    for key in ['imap_host','smtp_host']:
        host = cfg.get(key, '')
        if host not in ['imap.zoho.com','smtp.zoho.com','imap.zoho.eu','smtp.zoho.eu',
                        'imappro.zoho.com','smtppro.zoho.com']:
            raise ValueError('Use the actual supported Zoho mail server. No unknown mail hosts.')
    return cfg, password


def read_email(store):
    store.check_stop()
    cfg, password = email_config(store)
    total = 0
    client = imaplib.IMAP4_SSL(cfg['imap_host'], 993, ssl_context=ssl.create_default_context(), timeout=30)
    try:
        client.login(cfg['user'], password)
        status, _ = client.select('INBOX', readonly=True)
        if status != 'OK': raise RuntimeError('Cannot read INBOX')
        status, ids = client.uid('search', None, 'ALL')
        if status != 'OK': raise RuntimeError('Mail search failed')
        for ident in ids[0].split()[-25:]:
            store.check_stop()
            status, parts = client.uid('fetch', ident, '(BODY.PEEK[])')
            if status != 'OK': raise RuntimeError('Message fetch failed')
            raw = next((part[1] for part in parts if isinstance(part, tuple)), None)
            if raw is None: continue
            message = email.message_from_bytes(raw, policy=default)
            body_part = message.get_body(preferencelist=('plain',)) if message.is_multipart() else message
            text = body_part.get_content() if body_part and body_part.get_content_type() == 'text/plain' else '[No plain-text body; inspect mail manually]'
            if not isinstance(text, str): text = '[Non-text message]'
            record = json.dumps({'from': str(message.get('From','')), 'to': str(message.get('To','')),
                                 'subject': str(message.get('Subject','')), 'date': str(message.get('Date','')),
                                 'message_id': str(message.get('Message-ID','')), 'body': text[:20000]})
            url = 'imap://' + cfg['user'] + '/INBOX/' + ident.decode('ascii')
            if store.observe('Zoho Mail', url, record): total += 1
    finally:
        try: client.logout()
        except Exception: pass
    store.audit('email_read', new_messages=total)
    return total


def send_email(store, row):
    store.check_stop()
    cfg, password = email_config(store)
    recipient = row['recipient']
    if parseaddr(recipient)[1] != recipient or '@' not in recipient or any(x in recipient for x in '\r\n,;'):
        raise ValueError('One exact email address is required; no bulk recipients.')
    if row['target'] != 'mailto:' + recipient:
        raise ValueError('Email target and recipient differ.')
    if not row['subject'] or any(c in row['subject'] for c in '\r\n'):
        raise ValueError('A single-line subject is required.')
    message = EmailMessage()
    message['From'] = cfg['user']; message['To'] = recipient; message['Subject'] = row['subject']
    message.set_content(row['body'])
    # Establish authenticated connection BEFORE claiming, but do not send before claim.
    with smtplib.SMTP_SSL(cfg['smtp_host'], 465, context=ssl.create_default_context(), timeout=30) as client:
        client.login(cfg['user'], password)
        store.claim(row['id'])
        try:
            store.check_stop()
            refused = client.send_message(message)
            if refused: raise RuntimeError('Recipient refused')
            store.finish(row['id'], 'smtp_accepted', 'Mail server accepted; delivery is NOT proven.')
            print('Zoho SMTP accepted the message. This does not prove delivery.')
        except Exception:
            store.finish(row['id'], 'uncertain', 'Inspect Sent folder/provider before any retry.')
            raise


def desktop(store, operation, values):
    store.check_stop()
    import pyautogui as gui
    gui.FAILSAFE = True  # Move pointer to a screen corner to abort PyAutoGUI actions.
    gui.PAUSE = 0.5
    if operation == 'screenshot':
        path = store.data / ('screen_' + str(time.time_ns()) + '.png')
        gui.screenshot().save(path); print(path); return
    if operation == 'position':
        print(gui.position()); return
    print('Desktop action:', operation, json.dumps(values))
    print('Check the active window. Click/type/hotkeys can send, delete or change data.')
    if input('Type go desktop for ONLY this displayed action: ').strip() != 'go desktop':
        print('Cancelled.'); return
    store.check_stop()
    if operation == 'click' and len(values) == 2: gui.click(int(values[0]), int(values[1]))
    elif operation == 'type' and values:
        text = ' '.join(values)
        if not text.isascii() or any(c in text for c in '\r\n\t'):
            raise ValueError('ASCII text only; no Enter or Tab injection. Use browser editor for Unicode.')
        gui.write(text, interval=0.04)
    elif operation == 'hotkey' and 1 <= len(values) <= 3:
        gui.hotkey(*values)
    else: raise ValueError('Invalid desktop command')
    store.audit('owner_desktop_action', operation=operation)
